const trackingPixel = new Uint8Array([
  0x47, 0x49, 0x46, 0x38, 0x39, 0x61, 0x01, 0x00, 0x01, 0x00, 0x80, 0x00, 0x00, 0x00,
  0x00, 0x00, 0xff, 0xff, 0xff, 0x21, 0xf9, 0x04, 0x01, 0x00, 0x00, 0x00, 0x00, 0x2c,
  0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00, 0x02, 0x01, 0x44, 0x00, 0x3b,
]);

export function createTrackingPixelResponse(): Response {
  // This temporary endpoint intentionally reports zero while it retains the GIF body.
  return new Response(trackingPixel, {
    headers: {
      "Cache-Control": "no-store",
      "Content-Length": "0",
      "Content-Type": "image/gif",
    },
  });
}
